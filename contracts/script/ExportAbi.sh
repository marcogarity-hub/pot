#!/usr/bin/env bash
# Builds the contracts and writes Pot's ABI to web/lib/pot/abi.ts.
# Usage: contracts/script/ExportAbi.sh   (works from any directory)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONTRACTS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_DIR="$(cd "$CONTRACTS_DIR/.." && pwd)"
ARTIFACT="$CONTRACTS_DIR/out/Pot.sol/Pot.json"
OUT="$REPO_DIR/web/lib/pot/abi.ts"

command -v jq >/dev/null 2>&1 || { echo "ExportAbi: jq is required" >&2; exit 1; }

cd "$CONTRACTS_DIR"
arc-forge build

[ -f "$ARTIFACT" ] || { echo "ExportAbi: missing $ARTIFACT" >&2; exit 1; }

abi="$(jq '.abi' "$ARTIFACT")"
tmp="$(mktemp)"
{
  echo "// Generated by contracts/script/ExportAbi.sh — do not edit."
  printf 'export const potAbi = %s as const;\n' "$abi"
} > "$tmp"
chmod 644 "$tmp"
mv "$tmp" "$OUT"
echo "ExportAbi: wrote $OUT"
